/* global console */
// 生成小红书可售卖的模板文件包（投递追踪表 / 面试复盘 / 十周计划 / 面试题库）
// 输出：.edge-profile/template-pack/（复制到云盘即可用于上架薯店）
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const outDir = resolve(".edge-profile", "template-pack");
mkdirSync(outDir, { recursive: true });

const BOM = "\uFEFF";

// 1. 投递追踪表（CSV，Excel 直接打开；表头与 jobhunt-ops 投递 CSV 一致）
const appCsv = BOM + [
  "company,tier,channel,position,positionKind,status,deadline,appliedAt,url,note,nextAction",
  "示例公司A,冲刺,官网,量化研究员,量化研究,计划投递,2026-09-15,,https://example.com/job/1,投递后 3 天无动静就催,准备笔试",
  "示例公司B,主攻,牛客,量化开发,量化开发,已投递,2026-09-20,2026-08-25,,内推人:XX,复习 C++",
  "示例公司C,保底,应届生,数据分析,数据分析,笔试,2026-09-30,,,笔试时间等通知,刷概率题",
].join("\r\n");
writeFileSync(resolve(outDir, "01-投递追踪表.csv"), appCsv, "utf8");

// 2. 面试复盘模板（Markdown）
const reviewMd = `# 面试复盘模板（每次面试后 30 分钟内填写）

## 基本信息
- 公司：____　轮次：笔试 / 一面 / 二面 / 终面 / HR面　日期：____
- 岗位：____　面试官背景（如知道）：____

## 问题记录（逐题）
1. 问题：____
   我的回答：____
   更好的回答/标准答案：____
2. ...

## 四步复盘
1. **做得好**：____
2. **不足**：____（具体到知识点/表达/心态）
3. **下一步**：____（补什么知识、练什么题、约谁模拟）
4. **本题库沉淀**：把高频题/新题加入面试题库

---
*配套：jobhunt-ops 面试记录页可在线记录并自动汇总题库，详见使用说明。*
`;
writeFileSync(resolve(outDir, "02-面试复盘模板.md"), reviewMd, "utf8");

// 3. 十周计划模板（Markdown）
const planMd = `# 十周秋招计划模板（W1–W10）

> 原则：每周 1 个主题目标 + 5 个可勾选行动 + 1 次周复盘。任务要"小到能完成"。

## W1：地基（日期 ____）
- [ ] 投递 10 家（冲刺 3 / 主攻 5 / 保底 2）
- [ ] 简历 v1 完成 + 发给 2 个人反馈
- [ ] 笔试摸底：做 1 套概率题 + 1 套数据结构题
- [ ] 知识地图：列出 5 类知识现状（数学/统计、编程、金融量化、ML、面试准备）
- [ ] 周复盘（30 分钟）：本周投递漏斗数字

## W2：投递提速（日期 ____）
- [ ] 投递 15 家（用投递追踪表登记，含截止日和链接）
- [ ] 简历 v2（按反馈修改）
- [ ] 每天 1 道概率/期望题（共 7 道）
- [ ] 面试题库：建立空模板，记录第 1 场笔试的题
- [ ] 周复盘

## W3–W10：（按此结构复制，主题示例）
- W3 笔试攻坚 / W4 面经搜集 / W5 项目打磨 / W6 模拟面试 /
- W7 冲刺面试 / W8 复盘迭代 / W9 谈判准备 / W10 收官

---
*配套：jobhunt-ops 周计划页可在线勾选，进度自动统计。*
`;
writeFileSync(resolve(outDir, "03-十周计划模板.md"), planMd, "utf8");

